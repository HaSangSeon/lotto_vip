  /// 검색 로직: 입력한 단어가 포함된 키워드들을 반환.
  /// 만약 포함된 키워드가 하나도 없다면, 유저가 입력한 단어 그 자체를 유일한 결과로 반환 (Fallback 허용)
  static List<String> search(String query) {
    final trimmed = query.trim();
    if (trimmed.isEmpty) return popularKeywords.toList();
    final q = trimmed.toLowerCase();
    
    final matched = _dictionary.keys.where((key) {
      return key.toLowerCase().contains(q);
    }).toList();

    // 딕셔너리에 없으면 입력한 단어 자체를 반환 (해시 폴백 로직을 타기 위함, 최대 15자)
    if (matched.isEmpty) {
      final safeWord = trimmed.length > 15 ? trimmed.substring(0, 15) : trimmed;
      return [safeWord];
    }
    
    return matched;
  }

  /// 키워드를 입력받아 로또 번호 추출
  /// 사전에 있으면 사전 번호를 반환하고, 없으면 키워드의 글자값을 기반으로 '항상 똑같은 난수' 1~3개를 반환
  static List<int> getNumbers(String keyword) {
    if (_dictionary.containsKey(keyword)) {
      return _dictionary[keyword]!;
    }
    
    // 사전에 없는 단어는 문자열의 유니코드 해시값을 시드로 사용하여 고정된 난수를 추출
    int hash = 0;
    for (int i = 0; i < keyword.length; i++) {
      hash = (hash * 31 + keyword.codeUnitAt(i)) & 0x7FFFFFFF;
    }
    final random = Random(hash);
    
    // 2개의 고정수 추출
    final int count = 2; 
    
    final Set<int> fallbackNumbers = {};
    while (fallbackNumbers.length < count) {
      fallbackNumbers.add(random.nextInt(45) + 1);
    }
    
    final result = fallbackNumbers.toList()..sort();
    return result;
  }
